import { useCallback, useEffect, useMemo, useState } from "react";
import { Plus, Pencil, Trash2, Search, RefreshCw, FileSpreadsheet, Printer } from "lucide-react";
import { toast } from "sonner";
import { supabase } from "@/integrations/supabase/client";
import { Button } from "@/components/ui/button";
import { Card } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Textarea } from "@/components/ui/textarea";
import { Badge } from "@/components/ui/badge";
import { Dialog, DialogContent, DialogFooter, DialogHeader, DialogTitle } from "@/components/ui/dialog";
import {
  AlertDialog, AlertDialogAction, AlertDialogCancel, AlertDialogContent,
  AlertDialogDescription, AlertDialogFooter, AlertDialogHeader, AlertDialogTitle,
} from "@/components/ui/alert-dialog";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from "@/components/ui/table";

export type Row = Record<string, unknown>;

export type Field = {
  key: string;
  label: string;
  type?: "text" | "number" | "date" | "textarea" | "select" | "email";
  options?: { value: string; label: string }[];
  required?: boolean;
  placeholder?: string;
  /** Not shown in the create/edit form (computed or generated by the database). */
  readOnly?: boolean;
  /** Not shown in the table. */
  hideInTable?: boolean;
  /** Custom cell renderer. */
  render?: (row: Row) => React.ReactNode;
};

type Props = {
  table: string;
  title: string;
  description?: string;
  fields: Field[];
  /** Columns to select; defaults to "*". */
  select?: string;
  orderBy?: { column: string; ascending?: boolean };
  searchKeys?: string[];
  canCreate?: boolean;
  canEdit?: boolean;
  canDelete?: boolean;
  emptyLabel?: string;
  /** Client-side row filter, e.g. { doctor_id: "…" }. Also limits exports. */
  filter?: Record<string, unknown>;
  /** Values merged into every new record (and hidden from the form). */
  defaults?: Row;
  /** Show the CSV / PDF export buttons. */
  exportable?: boolean;
};

// The generated Supabase types are per-table literals; this manager is table-generic
// on purpose, so it uses a loosened view of the client for its dynamic queries.
type LooseClient = {
  from: (table: string) => {
    select: (columns: string) => {
      order: (column: string, opts: { ascending: boolean }) => PromiseLike<{ data: Row[] | null; error: { message: string } | null }>;
    };
    insert: (values: Row) => PromiseLike<{ error: { message: string } | null }>;
    update: (values: Row) => { eq: (col: string, val: unknown) => PromiseLike<{ error: { message: string } | null }> };
    delete: () => { eq: (col: string, val: unknown) => PromiseLike<{ error: { message: string } | null }> };
  };
};
const db = supabase as unknown as LooseClient;

function display(value: unknown): string {
  if (value === null || value === undefined || value === "") return "—";
  if (typeof value === "boolean") return value ? "Yes" : "No";
  if (typeof value === "object") return JSON.stringify(value);
  return String(value);
}

export function CrudManager({
  table, title, description, fields, select = "*", orderBy = { column: "created_at", ascending: false },
  searchKeys = [], canCreate = true, canEdit = true, canDelete = true, emptyLabel = "No records yet.",
  filter, defaults, exportable = true,
}: Props) {
  const [rows, setRows] = useState<Row[]>([]);
  const [loading, setLoading] = useState(true);
  const [query, setQuery] = useState("");
  const [editing, setEditing] = useState<Row | null>(null);
  const [open, setOpen] = useState(false);
  const [form, setForm] = useState<Record<string, string>>({});
  const [saving, setSaving] = useState(false);
  const [deleteTarget, setDeleteTarget] = useState<Row | null>(null);

  const load = useCallback(async () => {
    setLoading(true);
    const { data, error } = await db.from(table).select(select).order(orderBy.column, { ascending: orderBy.ascending ?? false });
    setLoading(false);
    if (error) { toast.error(error.message); return; }
    setRows(data ?? []);
  }, [table, select, orderBy.column, orderBy.ascending]);

  useEffect(() => { void load(); }, [load]);

  const editableFields = useMemo(() => fields.filter((f) => !f.readOnly), [fields]);
  const tableFields = useMemo(() => fields.filter((f) => !f.hideInTable), [fields]);

  const filterKey = JSON.stringify(filter ?? {});
  const filtered = useMemo(() => {
    const active = JSON.parse(filterKey) as Record<string, unknown>;
    let out = rows.filter((r) => Object.entries(active).every(([k, v]) => String(r[k] ?? "") === String(v ?? "")));
    const q = query.trim().toLowerCase();
    if (q) {
      const keys = searchKeys.length ? searchKeys : tableFields.map((f) => f.key);
      out = out.filter((r) => keys.some((k) => String(r[k] ?? "").toLowerCase().includes(q)));
    }
    return out;
  }, [rows, query, searchKeys, tableFields, filterKey]);

  const exportColumns = useMemo(
    () => tableFields.map((f) => ({ key: f.key, label: f.label })),
    [tableFields],
  );

  const openCreate = () => {
    setEditing(null);
    setForm(Object.fromEntries(editableFields.map((f) => [f.key, ""])));
    setOpen(true);
  };

  const openEdit = (row: Row) => {
    setEditing(row);
    setForm(Object.fromEntries(editableFields.map((f) => [f.key, row[f.key] == null ? "" : String(row[f.key])])));
    setOpen(true);
  };

  const save = async () => {
    for (const f of editableFields) {
      if (f.required && !form[f.key]?.trim()) { toast.error(`${f.label} is required.`); return; }
    }
    const payload: Row = {};
    for (const f of editableFields) {
      const raw = form[f.key]?.trim() ?? "";
      if (raw === "") { payload[f.key] = null; continue; }
      payload[f.key] = f.type === "number" ? Number(raw) : raw;
    }
    setSaving(true);
    const { error } = editing
      ? await db.from(table).update(payload).eq("id", editing["id"])
      : await db.from(table).insert({ ...(defaults ?? {}), ...payload });
    setSaving(false);
    if (error) { toast.error(error.message); return; }
    toast.success(editing ? "Record updated." : "Record created.");
    setOpen(false);
    void load();
  };

  const confirmDelete = async () => {
    if (!deleteTarget) return;
    const { error } = await db.from(table).delete().eq("id", deleteTarget["id"]);
    setDeleteTarget(null);
    if (error) { toast.error(error.message); return; }
    toast.success("Record deleted.");
    void load();
  };

  return (
    <Card className="rounded-3xl border-border/60 p-6 shadow-card">
      <div className="flex flex-wrap items-center justify-between gap-4">
        <div>
          <h2 className="text-lg font-semibold">{title}</h2>
          {description && <p className="text-sm text-muted-foreground">{description}</p>}
        </div>
        <div className="flex items-center gap-2">
          <div className="relative">
            <Search className="pointer-events-none absolute left-3 top-1/2 h-4 w-4 -translate-y-1/2 text-muted-foreground" />
            <Input value={query} onChange={(e) => setQuery(e.target.value)} placeholder="Search…" className="w-48 pl-9" />
          </div>
          <Button variant="ghost" size="icon" aria-label="Refresh" onClick={() => void load()}>
            <RefreshCw className="h-4 w-4" />
          </Button>
          {exportable && (
            <>
              <Button variant="outline" size="sm" className="rounded-full" onClick={() => exportCsv(table, exportColumns, filtered)}>
                <FileSpreadsheet className="mr-1 h-4 w-4" /> Excel
              </Button>
              <Button variant="outline" size="sm" className="rounded-full" onClick={() => { if (!exportPdf(title, exportColumns, filtered)) toast.error("Allow pop-ups to export the PDF."); }}>
                <Printer className="mr-1 h-4 w-4" /> PDF
              </Button>
            </>
          )}
          {canCreate && (
            <Button size="sm" className="rounded-full" onClick={openCreate}>
              <Plus className="mr-1 h-4 w-4" /> New
            </Button>
          )}
        </div>
      </div>

      <div className="mt-6 overflow-x-auto">
        <Table>
          <TableHeader>
            <TableRow>
              {tableFields.map((f) => <TableHead key={f.key}>{f.label}</TableHead>)}
              {(canEdit || canDelete) && <TableHead className="text-right">Actions</TableHead>}
            </TableRow>
          </TableHeader>
          <TableBody>
            {loading && (
              <TableRow><TableCell colSpan={tableFields.length + 1} className="py-10 text-center text-muted-foreground">Loading…</TableCell></TableRow>
            )}
            {!loading && filtered.length === 0 && (
              <TableRow><TableCell colSpan={tableFields.length + 1} className="py-10 text-center text-muted-foreground">{emptyLabel}</TableCell></TableRow>
            )}
            {!loading && filtered.map((row) => (
              <TableRow key={String(row["id"])}>
                {tableFields.map((f) => (
                  <TableCell key={f.key} className="max-w-[220px] truncate">
                    {f.render ? f.render(row) : display(row[f.key])}
                  </TableCell>
                ))}
                {(canEdit || canDelete) && (
                  <TableCell className="text-right">
                    {canEdit && (
                      <Button variant="ghost" size="icon" aria-label="Edit" onClick={() => openEdit(row)}>
                        <Pencil className="h-4 w-4" />
                      </Button>
                    )}
                    {canDelete && (
                      <Button variant="ghost" size="icon" aria-label="Delete" onClick={() => setDeleteTarget(row)}>
                        <Trash2 className="h-4 w-4 text-destructive" />
                      </Button>
                    )}
                  </TableCell>
                )}
              </TableRow>
            ))}
          </TableBody>
        </Table>
      </div>

      <div className="mt-4 text-xs text-muted-foreground">{filtered.length} record{filtered.length === 1 ? "" : "s"}</div>

      <Dialog open={open} onOpenChange={setOpen}>
        <DialogContent className="max-h-[85vh] overflow-y-auto sm:max-w-lg">
          <DialogHeader><DialogTitle>{editing ? `Edit ${title.toLowerCase()}` : `New ${title.toLowerCase()}`}</DialogTitle></DialogHeader>
          <div className="grid gap-4 sm:grid-cols-2">
            {editableFields.map((f) => (
              <div key={f.key} className={f.type === "textarea" ? "sm:col-span-2" : ""}>
                <Label htmlFor={`${table}-${f.key}`}>{f.label}{f.required && <span className="text-destructive"> *</span>}</Label>
                {f.type === "textarea" ? (
                  <Textarea id={`${table}-${f.key}`} className="mt-2" value={form[f.key] ?? ""} maxLength={2000}
                    onChange={(e) => setForm((s) => ({ ...s, [f.key]: e.target.value }))} />
                ) : f.type === "select" ? (
                  <Select value={form[f.key] ?? ""} onValueChange={(v) => setForm((s) => ({ ...s, [f.key]: v }))}>
                    <SelectTrigger id={`${table}-${f.key}`} className="mt-2"><SelectValue placeholder="Select…" /></SelectTrigger>
                    <SelectContent>
                      {(f.options ?? []).map((o) => <SelectItem key={o.value} value={o.value}>{o.label}</SelectItem>)}
                    </SelectContent>
                  </Select>
                ) : (
                  <Input id={`${table}-${f.key}`} className="mt-2" type={f.type === "number" ? "number" : f.type === "date" ? "date" : f.type === "email" ? "email" : "text"}
                    maxLength={f.type === "number" || f.type === "date" ? undefined : 255}
                    placeholder={f.placeholder} value={form[f.key] ?? ""}
                    onChange={(e) => setForm((s) => ({ ...s, [f.key]: e.target.value }))} />
                )}
              </div>
            ))}
          </div>
          <DialogFooter>
            <Button variant="ghost" onClick={() => setOpen(false)}>Cancel</Button>
            <Button onClick={() => void save()} disabled={saving}>{saving ? "Saving…" : "Save"}</Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>

      <AlertDialog open={!!deleteTarget} onOpenChange={(o) => !o && setDeleteTarget(null)}>
        <AlertDialogContent>
          <AlertDialogHeader>
            <AlertDialogTitle>Delete this record?</AlertDialogTitle>
            <AlertDialogDescription>This action cannot be undone.</AlertDialogDescription>
          </AlertDialogHeader>
          <AlertDialogFooter>
            <AlertDialogCancel>Cancel</AlertDialogCancel>
            <AlertDialogAction onClick={() => void confirmDelete()}>Delete</AlertDialogAction>
          </AlertDialogFooter>
        </AlertDialogContent>
      </AlertDialog>
    </Card>
  );
}

export function StatusCell({ value }: { value: unknown }) {
  const v = String(value ?? "");
  const tone = ["paid", "available", "discharged", "confirmed", "completed"].includes(v) ? "secondary" : "default";
  return <Badge variant={tone as "default" | "secondary"}>{v || "—"}</Badge>;
}